export type ShellLaunch = {
  /** Extra arguments for the shell process. */
  args: string[];
  /** Variables that must be added after the safe environment is built. */
  env: NodeJS.ProcessEnv;
};

export type ShellLaunchOptions = {
  /** Absolute path to the login shell, e.g. `/bin/bash`. */
  shell: string;
  /** Root of the task workspace. */
  root: string;
};

/**
 * Creates `<root>/.vinkup/shell` and refuses symlinks at either level. The
 * workspace is writable by the trainee's terminal, so following a link could
 * make the app overwrite a file outside the task folder.
 */
async function prepareShellDir(root: string): Promise<string> {
  const vinkupDir = path.join(root, '.vinkup');
  await mkdir(vinkupDir, { recursive: true });
  if (!(await lstat(vinkupDir)).isDirectory()) throw new Error('.vinkup is not a directory.');

  const dir = path.join(vinkupDir, 'shell');
  await mkdir(dir, { recursive: true });
  if (!(await lstat(dir)).isDirectory()) throw new Error('The shell directory is not a directory.');
  return dir;
}

/** Writes a generated file without following a symlink planted in the workspace. */
async function writeShellFile(dir: string, name: string, content: string): Promise<void> {
  const handle = await open(
    path.join(dir, name),
    constants.O_WRONLY | constants.O_CREAT | constants.O_TRUNC | constants.O_NOFOLLOW,
    0o600
  );
  try {
    await handle.writeFile(content, 'utf8');
  } finally {
    await handle.close();
  }
}

/**
 * Prepares a minimal prompt for the shells Vinkup supports. Other shells keep
 * their normal prompt: their startup files are not standardised, so overriding
 * them would risk breaking the trainee's configuration.
 *
 * The renderer never sees these files; they only affect the PTY in the main
 * process. A failure to write them falls back to the shell's normal prompt.
 */
export async function prepareShellLaunch(options: ShellLaunchOptions): Promise<ShellLaunch> {
  const name = path.basename(options.shell.trim());

  try {
    if (name === 'bash') {
      const dir = await prepareShellDir(options.root);
      const rcFile = path.join(dir, 'bashrc');
      await writeShellFile(dir, 'bashrc', BASH_RC);
      return { args: ['--rcfile', rcFile], env: {} };
    }

    if (name === 'zsh') {
      const dir = await prepareShellDir(options.root);
      await Promise.all([
        writeShellFile(dir, '.zshenv', ZSH_ENV),
        writeShellFile(dir, '.zshrc', ZSH_RC),
      ]);
      // zsh only reads .zshenv/.zshrc from ZDOTDIR; our files source the real ones.
      return { args: [], env: { ZDOTDIR: dir } };
    }
  } catch (error) {
    console.warn('[workspace] Could not prepare the terminal prompt', error);
  }

  return { args: [], env: {} };
}
