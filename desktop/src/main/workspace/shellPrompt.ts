import { constants } from 'node:fs';
import { lstat, mkdir, open } from 'node:fs/promises';
import path from 'node:path';

/**
 * A startup file that loads the trainee's own shell configuration first, so
 * aliases and functions still work, and then replaces only the prompt. The
 * workspace folder lives under the app's data directory, and printing that path
 * in every prompt is noise, so task terminals show a bare `vinkup$`.
 *
 * `cd` and `pushd` are wrapped so the task folder is the limit. A prompt hook
 * puts the shell back if a command bypasses the wrapper with `builtin cd`.
 */
const BASH_RC = `# Generated by Vinkup for task terminals; edit your own ~/.bashrc instead.
VINKUP_WORKSPACE_ROOT=$(pwd -P)

if [ -f "$HOME/.bashrc" ]; then
  . "$HOME/.bashrc"
fi

# The user's aliases must not bypass the guard below.
unalias cd pushd 2>/dev/null || true

vinkup_resolve() {
  local CDPATH=''
  builtin cd -- "$1" && pwd -P
}

vinkup_inside() {
  case "$1" in
    "$VINKUP_WORKSPACE_ROOT"|"$VINKUP_WORKSPACE_ROOT"/*) return 0 ;;
    *) return 1 ;;
  esac
}

vinkup_cd() {
  local option=''
  case "\${1:-}" in
    -P|-L)
      option="$1"
      shift
      ;;
    --)
      shift
      ;;
  esac

  local target
  if [ "$#" -eq 0 ]; then
    target="$VINKUP_WORKSPACE_ROOT"
  elif [ "$1" = "-" ]; then
    target="\${OLDPWD:-$VINKUP_WORKSPACE_ROOT}"
  else
    target="$1"
  fi

  local resolved
  if ! resolved=$(vinkup_resolve "$target"); then
    return 1
  fi
  if ! vinkup_inside "$resolved"; then
    printf 'vinkup: cannot leave the task folder\\n' >&2
    return 1
  fi
  if [ -n "$option" ]; then
    builtin cd "$option" -- "$resolved"
  else
    builtin cd -- "$resolved"
  fi
}

vinkup_pushd() {
  if [ "$#" -eq 0 ]; then
    builtin pushd >/dev/null
    return $?
  fi
  case "$1" in
    +*|-*)
      builtin pushd "$@"
      return $?
      ;;
  esac

  local resolved
  if ! resolved=$(vinkup_resolve "$1"); then
    return 1
  fi
  if ! vinkup_inside "$resolved"; then
    printf 'vinkup: cannot leave the task folder\\n' >&2
    return 1
  fi
  builtin pushd -- "$resolved" >/dev/null
}

vinkup_check_dir() {
  local current
  current=$(pwd -P) || return 0
  if vinkup_inside "$current"; then
    return 0
  fi
  printf 'vinkup: the task folder is the limit; returning to it.\\n' >&2
  builtin cd -- "$VINKUP_WORKSPACE_ROOT"
}

cd() { vinkup_cd "$@"; }
pushd() { vinkup_pushd "$@"; }

# Keep the generated prompt even if the user's config rewrites it.
# 256-colour 99 is a mid-tone purple with enough contrast on the light and dark
# terminal backgrounds.
PS1='\\[\\e[38;5;99m\\]vinkup\\[\\e[0m\\]\\$ '
PROMPT_COMMAND='vinkup_check_dir'

# A config that changed directory must not start the shell outside the task.
vinkup_check_dir
`;

